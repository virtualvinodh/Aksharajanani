import { describe, it, expect } from 'vitest';
import { getAutoGeneratedRules } from './feaService';
import { Character, GlyphData } from '../types';

// A user-added conjunct (no explicit feature) in a project whose script tag is one of the
// newer Indic tags. It must go into the Indic feature (akhn), not the generic `liga`, or
// Windows' Indic shaper never applies it.
const drawn: GlyphData = { paths: [{ id: 'p', type: 'pen', points: [{ x: 0, y: 0 }, { x: 10, y: 10 }] }] } as GlyphData;
const chars: Character[] = [
    { unicode: 0x0915, name: 'क' },
    { unicode: 0x094D, name: '्', glyphClass: 'mark' },
    { unicode: 0x0937, name: 'ष' },
    { unicode: 0xE900, name: 'क्ष_custom', glyphClass: 'ligature', liga: ['क', '्', 'ष'] },
];
const byUnicode = new Map(chars.map(c => [c.unicode!, c]));
const glyphs = new Map(chars.map(c => [c.unicode!, drawn]));

describe('Indic script tags (E8)', () => {
    for (const tag of ['dev2', 'knd2', 'gur2', 'deva', 'tml2']) {
        it(`puts a user ligature into akhn for ${tag}`, () => {
            expect(getAutoGeneratedRules(byUnicode, glyphs, 'akhn', tag).map(r => r.output)).toContain('क्ष_custom');
            expect(getAutoGeneratedRules(byUnicode, glyphs, 'liga', tag)).toHaveLength(0);
        });
    }
    it('keeps liga for non-Indic scripts', () => {
        expect(getAutoGeneratedRules(byUnicode, glyphs, 'liga', 'DFLT').map(r => r.output)).toContain('क्ष_custom');
    });
});
