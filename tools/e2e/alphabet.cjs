const seg = (x1, y1, x2, y2) => [[x1, y1], [x2, y2]];
// Elliptical arc; angles in degrees, 0 = right, 90 = down (canvas y grows downwards).
const arc = (cx, cy, rx, ry, a0, a1, n) => {
    const steps = n || Math.max(8, Math.round(Math.abs(a1 - a0) / 10));
    const out = [];
    for (let i = 0; i <= steps; i++) {
        const a = (a0 + (a1 - a0) * (i / steps)) * Math.PI / 180;
        out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
    }
    return out;
};
const poly = (...pts) => pts.slice(1).map((p, i) => [pts[i], p]); // polyline as separate straight strokes
